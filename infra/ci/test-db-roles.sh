#!/usr/bin/env bash
# Перевірка infra/db/roles.sql на PostgreSQL тієї ж версії, що в Azure, налаштованому як Azure:
# адмін без прав суперкористувача, схемою public володіє окрема роль (як azure_pg_admin).
# Перевіряє: скрипт проходить, marketplace_owner створює таблиці, marketplace_app працює з даними,
# але не змінює структуру, сторонній користувач до бази не підключається.
# Запуск з кореня репозиторію (потрібен Docker): bash infra/ci/test-db-roles.sh
set -euo pipefail
cd "$(dirname "$0")/../.."

IMAGE=postgres:17.11               # як в Azure
NAME=ci-pg-$$
FAILED=0

cleanup() { docker rm -f "$NAME" >/dev/null 2>&1 || true; }
trap cleanup EXIT

ok()   { echo "  ✓ $1"; }
fail() { echo "  ✗ $1"; FAILED=1; }

# psql по мережі з паролем — як підключається backend. Адреса контейнера, а не 127.0.0.1:
# з 127.0.0.1 образ PostgreSQL пускає без пароля, і паролі не перевірялися б
# pg <користувач> <пароль> <база> [аргументи psql]
pg() {
    local user=$1 pass=$2 db=$3; shift 3
    docker exec -i -e PGPASSWORD="$pass" "$NAME" \
        psql -h "$HOST" -U "$user" -d "$db" -v ON_ERROR_STOP=1 -qAtX "$@"
}
expect_ok()   { local what=$1; shift; if OUT=$("$@" 2>&1); then ok "$what"; else echo "$OUT"; fail "$what"; fi; }
expect_fail() { local what=$1; shift; if "$@" >/dev/null 2>&1; then fail "$what — мало бути заборонено"; else ok "$what — заборонено"; fi; }

echo "Образ: $IMAGE"
# Паролі тут лише для тимчасової тестової бази, не секрет
docker run -d --name "$NAME" -e POSTGRES_PASSWORD=ci_superuser \
    -v "$PWD/infra/db:/sql:ro" "$IMAGE" >/dev/null
for _ in $(seq 1 60); do
    docker exec "$NAME" pg_isready -h 127.0.0.1 -U postgres >/dev/null 2>&1 && break
    sleep 1
done
HOST=$(docker inspect -f '{{range .NetworkSettings.Networks}}{{.IPAddress}}{{end}}' "$NAME")

echo "1. База як в Azure"
pg postgres ci_superuser postgres -c "CREATE ROLE azure_pg_admin NOLOGIN" \
    -c "CREATE ROLE mpadmin LOGIN CREATEROLE CREATEDB PASSWORD 'ci_mpadmin'" \
    -c "GRANT azure_pg_admin TO mpadmin" \
    -c "CREATE ROLE ci_stranger LOGIN PASSWORD 'ci_stranger'"
pg postgres ci_superuser template1 -c "ALTER SCHEMA public OWNER TO azure_pg_admin"
ok "адмін без суперкористувача, public належить azure_pg_admin"

echo "2. roles.sql під адміном"
expect_ok "скрипт виконано без помилок" pg mpadmin ci_mpadmin postgres -f /sql/roles.sql
[[ $FAILED == 0 ]] || { echo "РЕЗУЛЬТАТ: roles.sql не виконався"; exit 1; }
pg mpadmin ci_mpadmin postgres -c "ALTER ROLE marketplace_owner PASSWORD 'ci_owner'" \
    -c "ALTER ROLE marketplace_app PASSWORD 'ci_app'"

echo "3. Паролі"
expect_ok   "свій пароль пускає"  pg marketplace_app ci_app marketplace -c "SELECT 1"
expect_fail "вхід з чужим паролем" pg marketplace_app ci_owner marketplace -c "SELECT 1"

echo "4. marketplace_owner — міграції"
expect_ok "створює таблиці (identity і serial)" pg marketplace_owner ci_owner marketplace \
    -c "CREATE TABLE ci_products (id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text)" \
    -c "CREATE TABLE ci_legacy (id serial PRIMARY KEY, v text)"

echo "5. marketplace_app — backend"
expect_ok "читає, додає, змінює, видаляє дані" pg marketplace_app ci_app marketplace \
    -c "INSERT INTO ci_products (name) VALUES ('a')" \
    -c "INSERT INTO ci_legacy (v) VALUES ('b')" \
    -c "UPDATE ci_products SET name = 'c'" \
    -c "SELECT count(*) FROM ci_products" \
    -c "DELETE FROM ci_legacy"
expect_fail "створити таблицю"     pg marketplace_app ci_app marketplace -c "CREATE TABLE ci_x (id int)"
expect_fail "змінити таблицю"      pg marketplace_app ci_app marketplace -c "ALTER TABLE ci_products ADD COLUMN x int"
expect_fail "очистити таблицю"     pg marketplace_app ci_app marketplace -c "TRUNCATE ci_products"
expect_fail "видалити таблицю"     pg marketplace_app ci_app marketplace -c "DROP TABLE ci_products"
expect_fail "створити розширення"  pg marketplace_app ci_app marketplace -c "CREATE EXTENSION pg_trgm"

echo "6. Сторонній користувач"
expect_fail "підключитися до бази marketplace" pg ci_stranger ci_stranger marketplace -c "SELECT 1"

if [[ $FAILED != 0 ]]; then echo "РЕЗУЛЬТАТ: є помилки"; exit 1; fi
echo "РЕЗУЛЬТАТ: усе ок"
